const palettes = [
  ['#29444e', '#e5d7ab', 'eye'],
  ['#753d40', '#f1dfc2', 'circles'],
  ['#c16b42', '#fff0ce', 'dunes'],
  ['#d6ad55', '#3d493a', 'leaves'],
  ['#537566', '#f1e7c8', 'leaves'],
  ['#467180', '#e8e0c8', 'waves'],
];

function demonstrationIsbn(index) {
  const digits = `978000${String(index + 1).padStart(6, '0')}`;
  const sum = [...digits].reduce((total, digit, i) => total + Number(digit) * (i % 2 ? 3 : 1), 0);
  return `${digits}${(10 - (sum % 10)) % 10}`;
}

export const additionalBooks = entries.map(
  ([title, author, genre, year, pages, description], index) => {
    const [color, ink, art] = palettes[index % palettes.length];
    return {
      id: `collection-${index + 1}`,
      title,
      author,
      genre,
      year,
      pages,
      description,
      isbn: demonstrationIsbn(index),
      copies: index % 9 === 8 ? 0 : 1 + (index % 4),
      color,
      ink,
      art,
      popularity: 90 - index,
    };
  },
);
